#!/usr/bin/env python3
"""Builds every brainrot's model texture and Java layout from tools/art/brainrots/<kind>.py.

    python tools/art/generate_brainrots.py [--preview DIR] [--only kind,kind]

Each kind module has ``build() -> (M, paint)`` (see brainrots/kit.py and brainrots/tung_tung_sahur.py, the example).
For every kind this packs the cubes, paints the texture, and writes:

    brainrots/src/main/resources/assets/skyrpg_brainrots/textures/entity/<kind>.png   (+ <kind>_glow.png when it glows)
    brainrots/src/client/java/com/skyrpg/brainrots/client/model/<Kind>Layout.java

``--preview DIR`` also renders one sheet with every brainrot (front 3/4, side, back) into DIR/brainrots_preview.png.
Model conventions (what BrainrotModel animates by name): parts "body" (required), "head", "leg_r", "leg_l", "leg_m",
"arm_r", "arm_l", "wing_r", "wing_l", "tail", "ring" (spins), "prop" / "prop_r" / "prop_l" (spin), "ear_r", "ear_l".
"""
import importlib
import math
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "brainrots"))
import cube_model as cm  # noqa: E402

ROOT = HERE.parents[1]
TEX_DIR = ROOT / "brainrots/src/main/resources/assets/skyrpg_brainrots/textures/entity"
JAVA_DIR = ROOT / "brainrots/src/client/java/com/skyrpg/brainrots/client/model"

# Order of the album (and of BrainrotKind).
KINDS = [
    "tung_tung_sahur", "tralalero_tralala", "bombardiro_crocodilo", "ballerina_cappuccina", "brr_brr_patapim",
    "lirili_larila", "chimpanzini_bananini", "bombombini_gusini", "trippi_troppi", "cappuccino_assassino",
    "frigo_camelo", "la_vaca_saturno", "boneca_ambalabu", "glorbo_fruttodrillo", "burbaloni_luliloli",
]


def camel(kind):
    return "".join(w.capitalize() for w in kind.split("_"))


def has_pixels(img):
    return img is not None and img.getbbox() is not None


def write_index():
    """BrainrotLayouts.java: every kind that has a layout, so the mod can find them (rewritten from the files present)."""
    kinds = [k for k in KINDS if (JAVA_DIR / f"{camel(k)}Layout.java").exists()]
    cases = "\n".join(f'            case "{k}" -> new Entry({camel(k)}Layout.create(), {camel(k)}Layout.PARTS, {camel(k)}Layout.GLOW);'
                      for k in kinds)
    text = (
        "package com.skyrpg.brainrots.client.model;\n\n"
        "import net.minecraft.client.model.geom.builders.LayerDefinition;\n\n"
        "/**\n"
        " * Every brainrot model that has been drawn. GENERATED by tools/art/generate_brainrots.py from the layouts present:\n"
        " * don't edit it by hand.\n"
        " */\n"
        "public final class BrainrotLayouts {\n"
        "    /** A kind's cubes, its part paths (\"body/head\"), and whether it has a glow texture. */\n"
        "    public record Entry(LayerDefinition layer, String[] parts, boolean glow) {\n"
        "    }\n\n"
        "    private BrainrotLayouts() {\n"
        "    }\n\n"
        "    /** The kind's model, or null when it hasn't been drawn yet. */\n"
        "    public static Entry get(String kind) {\n"
        "        return switch (kind) {\n"
        f"{cases}\n"
        "            default -> null;\n"
        "        };\n"
        "    }\n"
        "}\n")
    (JAVA_DIR / "BrainrotLayouts.java").write_text(text, encoding="utf-8", newline="\n")


def main():
    only = None
    if "--only" in sys.argv:
        only = set(sys.argv[sys.argv.index("--only") + 1].split(","))
    TEX_DIR.mkdir(parents=True, exist_ok=True)
    JAVA_DIR.mkdir(parents=True, exist_ok=True)
    built = []
    for kind in KINDS:
        if only and kind not in only:
            continue
        try:
            module = importlib.import_module(kind)
        except ModuleNotFoundError:
            print(f"  {kind}: not drawn yet")
            continue
        M, paint = module.build()
        M.pack(sizes=(64, 128))
        img, glow = paint(M)
        img.save(TEX_DIR / f"{kind}.png")
        glow_path = TEX_DIR / f"{kind}_glow.png"
        if has_pixels(glow):
            glow.save(glow_path)
        elif glow_path.exists():
            glow_path.unlink()
        name = camel(kind)
        # The model finds parts by name: every part's path from the root ("body/head"), and whether there's a glow texture.
        parents = {pt["name"]: pt["parent"] for pt in M.parts}

        def path(n):
            return n if parents[n] is None else path(parents[n]) + "/" + n
        paths = ", ".join(f'"{path(pt["name"])}"' for pt in M.parts)
        extra = (f"    static final String[] PARTS = {{{paths}}};\n"
                 f"    static final boolean GLOW = {'true' if has_pixels(glow) else 'false'};\n\n")
        (JAVA_DIR / f"{name}Layout.java").write_text(
            M.java("com.skyrpg.brainrots.client.model", f"{name}Layout", f"tools/art/brainrots/{kind}.py", name, extra=extra),
            encoding="utf-8", newline="\n")
        print(f"  {kind}: {len(M.cubes)} cubes, {M.width}x{M.height}, parts {[p['name'] for p in M.parts]}")
        built.append((kind, M, img, glow if has_pixels(glow) else None))
    write_index()
    if "--preview" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--preview") + 1])
        out.mkdir(parents=True, exist_ok=True)
        rows = []
        for kind, M, img, glow in built:
            height = max(8.0, max(-c["pos"][1] for c in M.cubes) + 24)
            scale = min(9.0, 230 / max(30.0, height + 12))
            r = lambda **kw: cm.render(M, img, glow, look_at=(0, 24 - height / 2, 0), scale=scale, size=(240, 240), center=(0.5, 0.5), **kw)
            rows.append(cm.sheet([r(yaw=0.55, pitch=0.35), r(yaw=math.pi / 2, pitch=0.1), r(yaw=2.6, pitch=0.4),
                                  cm.texture_sheet(img, glow if glow is not None else Image.new("RGBA", img.size),
                                                   zoom=max(1, 240 // max(M.width, M.height)))],
                                 [f"{kind} front", "side", "back", "texture"]))
        if rows:
            cm.stack(rows).save(out / "brainrots_preview.png")
            print("wrote", out / "brainrots_preview.png")


if __name__ == "__main__":
    main()
